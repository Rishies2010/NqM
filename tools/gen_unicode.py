#!/usr/bin/env python3
"""Generate src/unicode_tables.rs: ranges for \\p{L} and \\p{N} from Python's unicodedata.

The byte-level BPE pre-tokenizers of Llama 3 / Qwen / GPT-2 use \\p{L} and \\p{N}; Rust's
core has no such properties, so the tables are given. Re-run when you want a newer Unicode.
"""

import sys
import unicodedata


def ranges(first_letter):
    out, start, prev = [], None, None
    for cp in range(0x110000):
        hit = unicodedata.category(chr(cp)).startswith(first_letter)
        if hit and start is None:
            start = cp
        if not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, rs):
    lines = [f"pub static {name}: [(u32, u32); {len(rs)}] = ["]
    row = []
    for a, b in rs:
        row.append(f"(0x{a:X}, 0x{b:X})")
        if len(row) == 6:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("];")
    return "\n".join(lines)


out = sys.argv[1] if len(sys.argv) > 1 else "src/unicode_tables.rs"
with open(out, "w") as f:
    f.write(f"// @generated by tools/gen_unicode.py (Unicode {unicodedata.unidata_version}). Do not edit.\n")
    f.write("// Inclusive code point ranges: general category L* (letters) and N* (numbers).\n\n")
    f.write(emit("LETTER", ranges("L")) + "\n\n")
    f.write(emit("NUMBER", ranges("N")) + "\n")
print("wrote", out)
